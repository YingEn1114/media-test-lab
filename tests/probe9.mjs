import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost/accounts/login/', { waitUntil: 'networkidle' });
await page.locator('#id_login').fill('admin');
await page.locator('#id_password').fill('MediaCMS@123');
await page.getByRole('button', { name: 'Sign In' }).click();
await page.waitForLoadState('networkidle');
await page.goto('http://localhost/view?m=juMSnf8VT', { waitUntil: 'networkidle' });
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await page.waitForTimeout(500);
const ta = page.locator('textarea').first();
await ta.fill('E2E 评论 ' + Date.now());
const btn = page.getByRole('button', { name: '提交' });
console.log('disabled before:', await btn.isDisabled());
await btn.click();
await page.waitForTimeout(2000);
console.log('BODY TAIL:', (await page.locator('body').innerText()).slice(-400).replace(/\n/g,' | '));
await browser.close();
